func TestParsePrimaryCatalogFields(t *testing.T) {
	xmlDoc := `<?xml version="1.0" encoding="UTF-8"?>
<metadata xmlns="http://linux.duke.edu/metadata/common" xmlns:rpm="http://linux.duke.edu/metadata/rpm" packages="2">
<package type="rpm">
  <name>harbour-demo</name>
  <arch>aarch64</arch>
  <version epoch="0" ver="1.2.3" rel="4"/>
  <checksum type="sha" pkgid="YES">abc</checksum>
  <summary>Demo app</summary>
  <description>A longer description</description>
  <time file="10" build="1700000000"/>
  <size package="10" installed="20" archive="20"/>
  <location href="h/harbour-demo-1.2.3-4.aarch64.rpm"/>
  <format>
    <rpm:license>GPLv3</rpm:license>
    <rpm:sourcerpm>harbour-demo-1.2.3-4.src.rpm</rpm:sourcerpm>
    <rpm:provides>
      <rpm:entry name="harbour-demo" flags="EQ" epoch="0" ver="1.2.3" rel="4"/>
      <rpm:entry name="application()"/>
      <rpm:entry name="application(harbour-demo.desktop)"/>
    </rpm:provides>
    <rpm:requires>
      <rpm:entry name="sailfishsilica-qt5" flags="GE" epoch="0" ver="0.10.9"/>
      <rpm:entry name="rpmlib(CompressedFileNames)" flags="LE" epoch="0" ver="3.0.4" rel="1"/>
      <rpm:entry name="libfoo.so.1()(64bit)"/>
    </rpm:requires>
    <file>/usr/share/applications/harbour-demo.desktop</file>
  </format>
</package>
<package type="rpm">
  <name>harbour-demo-debuginfo</name>
  <arch>aarch64</arch>
  <version epoch="0" ver="1.2.3" rel="4"/>
  <checksum type="sha" pkgid="YES">def</checksum>
  <summary>Debug information for package harbour-demo</summary>
  <description>debug</description>
  <size package="3" installed="3" archive="3"/>
  <location href="h/harbour-demo-debuginfo-1.2.3-4.aarch64.rpm"/>
  <format>
    <rpm:sourcerpm>harbour-demo-1.2.3-4.src.rpm</rpm:sourcerpm>
    <rpm:requires>
      <rpm:entry name="rpmlib(FileDigests)" flags="LE" epoch="0" ver="4.6.0" rel="1"/>
    </rpm:requires>
  </format>
</package>
</metadata>`
	pkgs, err := parsePrimaryXML(strings.NewReader(xmlDoc))
	if err != nil {
		t.Fatal(err)
	}
	if len(pkgs) != 2 {
		t.Fatalf("packages %d", len(pkgs))
	}
	got := pkgs[0]
	if got.Summary != "Demo app" || got.Description != "A longer description" || got.Version != "1.2.3" || got.Release != "4" {
		t.Fatalf("text %+v", got)
	}
	if got.Source != "harbour-demo-1.2.3-4.src.rpm" || got.Build != 1700000000 || !got.App {
		t.Fatalf("origin %+v", got)
	}
	if len(got.Requires) != 3 || got.Requires[0] != "sailfishsilica-qt5" {
		t.Fatalf("requires %#v", got.Requires)
	}
	if pkgs[1].App || pkgs[1].Name != "harbour-demo-debuginfo" {
		t.Fatalf("debug %+v", pkgs[1])
	}
}

func TestParsePrimaryNoneBuildTime(t *testing.T) {
	xmlDoc := `<metadata xmlns="http://linux.duke.edu/metadata/common" xmlns:rpm="http://linux.duke.edu/metadata/rpm">
<package type="rpm"><name>taskwarrior</name><arch>aarch64</arch>
<version epoch="0" ver="2.6.2" rel="0"/>
<checksum type="sha" pkgid="YES">abc</checksum>
<summary>RPM archive generated by GNU Guix.</summary>
<time file="1702165431" build="None"/>
<size package="32793444" installed="100817317" archive="None"/>
<location href="t/taskwarrior-2.6.2-0.aarch64.rpm"/>
<format><rpm:sourcerpm>(none)</rpm:sourcerpm></format>
</package></metadata>`
	pkgs, err := parsePrimaryXML(strings.NewReader(xmlDoc))
	if err != nil {
		t.Fatal(err)
	}
	if len(pkgs) != 1 || pkgs[0].Build != 0 || pkgs[0].Size != 32793444 || pkgs[0].Source != "(none)" {
		t.Fatalf("%+v", pkgs)
	}
	if sourceName(pkgs[0].Source, pkgs[0].Name) != "taskwarrior" {
		t.Fatalf("source %s", sourceName(pkgs[0].Source, pkgs[0].Name))
	}
}

func TestAssembleCatalogGroupsSourceRPMs(t *testing.T) {
	when := time.Date(2026, 9, 28, 12, 0, 0, 0, time.UTC)
	doc := assembleCatalog([]catalogSource{
		{
			Publisher: "piggz",
			Updated:   when,
			RPMs: []pkgRef{
				{
					Name: "harbour-demo", Arch: "aarch64", Version: "1.2.3", Release: "4",
					Summary: "Demo app", Description: "A longer description",
					Source: "harbour-demo-1.2.3-4.src.rpm", Build: 1700000000, App: true,
					Requires: []string{"sailfishsilica-qt5", "rpmlib(CompressedFileNames)", "libfoo.so.1()(64bit)", "sailfishsilica-qt5"},
					SHA256:   "abc123",
					Href:     "h/harbour-demo-1.2.3-4.aarch64.rpm",
				},
				{
					Name: "harbour-demo-debuginfo", Arch: "aarch64", Version: "1.2.3", Release: "4",
					Summary: "debug", Source: "harbour-demo-1.2.3-4.src.rpm",
					Requires: []string{"rpmlib(FileDigests)"},
				},
				{
					Name: "harbour-demo", Arch: "src", Version: "1.2.3", Release: "4",
					Source: "harbour-demo-1.2.3-4.src.rpm",
				},
				{
					Name: "quiet", Arch: "noarch", Version: "0.1", Release: "1",
					Summary: "Just a library", Source: "quiet-0.1-1.src.rpm", Build: 1600000000,
				},
			},
		},
		{Publisher: "empty", Updated: when},
	}, nil)
	if doc.Version != 1 || doc.Updated != "2023-11-14T22:13:20Z" {
		t.Fatalf("header %#v", doc.Updated)
	}
	if len(doc.Categories) != 2 || len(doc.Repositories) != 1 {
		t.Fatalf("repos %#v categories %#v", doc.Repositories, doc.Categories)
	}
	if doc.Repositories[0].ID != "openrepos-piggz" || doc.Repositories[0].URL != "https://repo-openrepos.ftuna.eu/piggz/personal/main/" {
		t.Fatalf("repo %#v", doc.Repositories[0])
	}
	if len(doc.Packages) != 2 {
		t.Fatalf("packages %d", len(doc.Packages))
	}
	app := doc.Packages[0]
	if app.ID != "openrepos.net/piggz/harbour-demo" || app.Category != "application" || app.Repo != "openrepos-piggz" {
		t.Fatalf("app %#v", app)
	}
	if app.Summary != "Demo app" || app.Description != aibadge.Append("A longer description", "") || app.Icon != "" || len(app.Screenshots) != 0 {
		t.Fatalf("text %#v", app)
	}
	if app.Status.Sailjail != "unknown" || len(app.Status.Setuid) != 0 {
		t.Fatalf("status %#v", app.Status)
	}
	if len(app.RPMs) != 2 || !app.RPMs[0].Install || app.RPMs[1].Install || app.RPMs[1].Name != "harbour-demo-debuginfo" {
		t.Fatalf("rpms %#v", app.RPMs)
	}
	if app.RPMs[0].SHA256 != "abc123" || app.RPMs[0].Href != "h/harbour-demo-1.2.3-4.aarch64.rpm" {
		t.Fatalf("sha256 %#v", app.RPMs[0])
	}
	if strings.Join(app.RPMs[0].Requires, ",") != "sailfishsilica-qt5,libfoo.so.1()(64bit)" {
		t.Fatalf("requires %#v", app.RPMs[0].Requires)
	}
	lib := doc.Packages[1]
	if lib.ID != "openrepos.net/piggz/quiet" || lib.Category != "library" || lib.Updated != "2020-09-13T12:26:40Z" {
		t.Fatalf("lib %#v", lib)
	}
}

func TestAssembleCatalogUsesAppBackup(t *testing.T) {
	when := time.Date(2026, 9, 28, 12, 0, 0, 0, time.UTC)
	icon := "https://cdn-mirror.ftuna.eu/openrepos.net/sites/default/files/packages/1/icon.png"
	shot := "https://cdn-mirror.ftuna.eu/openrepos.net/sites/default/files/packages/1/shot.png"
	doc := assembleCatalog([]catalogSource{{
		Publisher: "piggz",
		Updated:   when,
		RPMs: []pkgRef{{
			Name: "harbour-demo", Arch: "aarch64", Version: "1.2.3", Release: "4",
			Summary: "Demo app", Description: "A longer description",
			Source: "harbour-demo-1.2.3-4.src.rpm", Build: 1700000000, App: true,
		}},
	}}, map[string]appBackup{
		"piggz\nharbour-demo": {
			Title:       "Lighthouse",
			Description: "<p>Hello&nbsp;world</p><p>More</p>",
			Icon:        icon,
			Screenshots: []string{shot, "https://openrepos.net/sites/default/files/packages/1/shot.png"},
		},
	})
	app := doc.Packages[0]
	if app.Summary != "Lighthouse" || app.Description != aibadge.Append("Hello world\nMore", "") || app.Category != "application" {
		t.Fatalf("text %#v", app)
	}
	if app.Icon != icon || len(app.Screenshots) != 1 || app.Screenshots[0] != shot {
		t.Fatalf("images %#v", app)
	}
}

